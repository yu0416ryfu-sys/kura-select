export function uniqueStrings(values: Array<string | null | undefined>): string[] {
  return [...new Set(values.map(v => String(v ?? '').trim()).filter(Boolean))];
}

export function getAdditionSearchRule(category: string, baseKeyword: string): ResolvedSearchRule {
  const rule = getArticleSpecificAdditionRule(category, baseKeyword) ?? CATEGORY_SEARCH_RULES[category] ?? {};
  const keywords = uniqueStrings([
    ...(rule.keywords ?? []),
    baseKeyword,
    `${baseKeyword} 大容量`,
    `${baseKeyword} まとめ買い`,
  ]).slice(0, 3);

  return {
    keywords,
    include: rule.include ?? [baseKeyword],
    exclude: [...DEFAULT_EXCLUDE_TERMS, ...(rule.exclude ?? [])],
    units: rule.units ?? null,
    minScore: rule.minScore ?? 4,
    requireInclude: rule.requireInclude ?? true,
    requiredGroups: rule.requiredGroups ?? [],
  };
}

export function isAllowedCapacityUnit(capacity: string, rule: ResolvedSearchRule): boolean {
  if (!rule.units) return true;
  const parsed = extractCapacityTotal(capacity);
  if (!parsed) return false;
  return rule.units.some(unit => unit.toLowerCase() === parsed.unit.toLowerCase());
}

export function candidateText(candidate: RuleCandidate): string {
  return String(candidate.name ?? '').normalize('NFKC').toLowerCase();
}

export function normalizedTerm(term: string | null | undefined): string {
  return String(term ?? '').normalize('NFKC').toLowerCase();
}

export function findTermHits(text: string, terms: string[]): string[] {
  return terms.filter(term => text.includes(normalizedTerm(term)));
}

/**
 * 除外語の部分一致の例外。
 *
 * 除外語がより長い語の一部として現れているだけの場合は、除外扱いにしない。
 * 例: `mosquito-repellent-liquid` の除外語 'マット'（ベープマット等の器具）が
 * 主題語である 'ノーマット' に部分一致して、本体の取替えボトルまで落としてしまう。
 * 記事別ルールでは回避できないため、ここで例外として扱う（Phase 0.5 / N10）。
 */
const EXCLUDE_TERM_EXCEPTIONS: Record<string, string[]> = {
  'マット': ['ノーマット'],
};

/**
 * 除外語のヒットを求める。EXCLUDE_TERM_EXCEPTIONS に載る語は、
 * 例外語の内側にしか出現しない場合ヒットとみなさない。
 */
export function findExcludeTermHits(text: string, terms: string[]): string[] {
  return terms.filter(term => {
    const needle = normalizedTerm(term);
    if (!needle || !text.includes(needle)) return false;

    const exceptions = EXCLUDE_TERM_EXCEPTIONS[term];
    if (!exceptions) return true;

    // 例外語が占める区間を塗りつぶし、そこに含まれない出現があるかを見る
    const covered = new Array(text.length).fill(false);
    for (const exception of exceptions) {
      const phrase = normalizedTerm(exception);
      if (!phrase) continue;
      let at = text.indexOf(phrase);
      while (at !== -1) {
        for (let i = at; i < at + phrase.length; i++) covered[i] = true;
        at = text.indexOf(phrase, at + 1);
      }
    }
    let at = text.indexOf(needle);
    while (at !== -1) {
      let inside = false;
      for (let i = at; i < at + needle.length; i++) {
        if (covered[i]) { inside = true; break; }
      }
      if (!inside) return true;
      at = text.indexOf(needle, at + 1);
    }
    return false;
  });
}

export function findRequiredGroupHits(text: string, groups: string[][] = []): RequiredGroupHit[] {
  return groups.map(group => ({
    group,
    hits: findTermHits(text, group),
  }));
}

export function checkAdditionCandidateCategory(candidate: RuleCandidate, rule: ResolvedSearchRule): { ok: boolean; reason: string | null } {
  const text = candidateText(candidate);
  const includeHits = findTermHits(text, rule.include);
  const excludeHits = findExcludeTermHits(text, rule.exclude);
  const requiredGroupHits = findRequiredGroupHits(text, rule.requiredGroups);

  if (excludeHits.length > 0) {
    return { ok: false, reason: `除外語: ${excludeHits.slice(0, 3).join(', ')}` };
  }
  const missingRequired = requiredGroupHits.find(group => group.hits.length === 0);
  if (missingRequired) {
    return { ok: false, reason: `必須語なし: ${missingRequired.group.slice(0, 3).join('/')}` };
  }
  if (rule.requireInclude && includeHits.length === 0) {
    return { ok: false, reason: 'カテゴリ語なし' };
  }

  return { ok: true, reason: null };
}

export function getAdditionCandidateDiagnostics(candidate: RuleCandidate, rule: ResolvedSearchRule): { includeHits: string[]; excludeHits: string[]; requiredGroupHits: RequiredGroupHit[] } {
  const text = candidateText(candidate);
  return {
    includeHits: findTermHits(text, rule.include),
    excludeHits: findExcludeTermHits(text, rule.exclude),
    requiredGroupHits: findRequiredGroupHits(text, rule.requiredGroups),
  };
}

export function scoreAdditionCandidate(candidate: RuleCandidate, rule: ResolvedSearchRule): { score: number; reasons: string[] } {
  const text = candidateText(candidate);
  const reasons = [];
  let score = 0;

  const includeHits = findTermHits(text, rule.include);
  if (includeHits.length > 0) {
    score += 3 + Math.min(includeHits.length - 1, 2);
    reasons.push(`カテゴリ語: ${includeHits.slice(0, 3).join(', ')}`);
  }
  const requiredGroupHits = findRequiredGroupHits(text, rule.requiredGroups);
  for (const group of requiredGroupHits) {
    if (group.hits.length > 0) {
      score += 2;
      reasons.push(`必須語: ${group.hits.slice(0, 2).join(', ')}`);
    }
  }

  const excludeHits = findExcludeTermHits(text, rule.exclude);
  if (excludeHits.length > 0) {
    score -= 4 * excludeHits.length;
    reasons.push(`除外語: ${excludeHits.slice(0, 3).join(', ')}`);
  }

  if (candidate.price !== null) {
    score += 1;
    reasons.push('価格あり');
  }
  if ((candidate.reviewCount ?? 0) >= 1000) score += 3;
  else if ((candidate.reviewCount ?? 0) >= 300) score += 2;
  else if ((candidate.reviewCount ?? 0) >= 50) score += 1;

  if ((candidate.rating ?? 0) >= 4.5) score += 2;
  else if ((candidate.rating ?? 0) >= 4.0) score += 1;

  return { score, reasons };
}

/**
 * 記事から baseKeyword と検索ルールをまとめて解決する。
 *
 * baseKeyword の導出規則ごと共有することで、記事をスキャンするツール側と
 * update-products 本体が別のルールを解決してしまうのを防ぐ（Phase 0.5 / N8）。
 */
export function resolveArticleSearchRule(article: {
  title?: string | null;
  products?: Array<{ name: string }>;
  file: string;
  category: string;
}): { baseKeyword: string; rule: ResolvedSearchRule } {
  const baseKeyword = buildArticleSearchKeyword(
    article.title ?? article.products?.[0]?.name ?? article.file
  );
  return { baseKeyword, rule: getAdditionSearchRule(article.category, baseKeyword) };
}
